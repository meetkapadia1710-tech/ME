/**
 * Design Tokens
 * 
 * This file documents the core design values used across the application.
 * Values here correspond to Tailwind classes defined in `tailwind.config.ts`
 * and CSS variables in `globals.css`.
 * 
 * ## Typography Scale (Font Size + Line Height + Tracking)
 * - `text-meta-sm`: 10px, 0.15em tracking. Used for tiny badges, very small ui elements.
 * - `text-meta`: 11px, 0.15em tracking. Used for section labels, timestamps, small metadata.
 * - `text-body-sm`: 14px. Used for secondary prose, card descriptions.
 * - `text-body`: 16px. Used for main body prose.
 * - `text-heading-sm`: 20px. Used for small section titles, card headers.
 * - `text-heading-md`: 24px. Used for standard section headings.
 * - `text-heading-lg`: 36px. Used for major section titles.
 * - `text-display`: 40px-64px (fluid). Used for Hero typography.
 * 
 * ## Colors
 * - `text-fg-primary`: Solid text color (#ece9e1)
 * - `text-fg-muted`: Muted/secondary text (rgba(236, 233, 225, 0.6))
 * - `bg-surface`: Subtle card/surface backgrounds (rgba(255, 255, 255, 0.05))
 * 
 * ## Spacing & Layout
 * - Use standard Tailwind spacing (e.g., `py-24`, `md:py-32` for sections).
 * - Section widths should be capped optimally for ultra-wide screens using max-w variants.
 */
